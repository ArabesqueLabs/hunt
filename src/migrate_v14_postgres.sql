-- Schema 13 to 14 (PostgreSQL): lanes. See migrate_v14.sql.
CREATE TABLE lane (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id   BIGINT NOT NULL REFERENCES stage(id) ON DELETE CASCADE,
    name       TEXT NOT NULL,
    position   BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX lane_by_stage ON lane (stage_id, position);
ALTER TABLE process ADD COLUMN lane_id BIGINT REFERENCES lane(id) ON DELETE SET NULL;
