-- hunt schema for PostgreSQL, version 11: the same tables as schema.sql
-- (SQLite), which explains them. Differences: ids are identities, files are
-- bytea, numbers are bigint, and names that must be unique regardless of
-- case have a unique index on lower(name).

CREATE TABLE hunt_meta (
    name  TEXT PRIMARY KEY,
    value TEXT
);

CREATE TABLE stage (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL,
    position   BIGINT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX stage_name ON stage (lower(name));

-- A stage's column divided by outcome (Offer: accepted, shortlisted,
-- rejected): its lanes, top to bottom. A process may be in one of its
-- stage's lanes; none is the column's undivided top.
CREATE TABLE lane (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id   BIGINT NOT NULL REFERENCES stage(id) ON DELETE CASCADE,
    name       TEXT NOT NULL,
    position   BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX lane_by_stage ON lane (stage_id, position);

CREATE TABLE stored_file (
    sha256 TEXT PRIMARY KEY,
    data   BYTEA NOT NULL
);

CREATE TABLE company (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL,
    kind          TEXT NOT NULL DEFAULT 'employer' CHECK (kind IN ('employer', 'agency')),
    website       TEXT,
    note          TEXT,
    created_at    TEXT NOT NULL,
    updated_at    TEXT NOT NULL,
    linkedin      TEXT,
    description   TEXT,
    industry      TEXT,
    size          TEXT,
    headquarters  TEXT,
    founded       TEXT,
    logo          TEXT REFERENCES stored_file(sha256),
    logo_type     TEXT,
    email_domains TEXT
);
CREATE UNIQUE INDEX company_name ON company (lower(name));

CREATE TABLE person (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL,
    company_id BIGINT REFERENCES company(id) ON DELETE SET NULL,
    title      TEXT,
    email      TEXT,
    phone      TEXT,
    link       TEXT,
    note       TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    linkedin   TEXT,
    location   TEXT,
    about      TEXT,
    photo      TEXT REFERENCES stored_file(sha256),
    photo_type TEXT
);

CREATE TABLE application (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id     BIGINT NOT NULL REFERENCES company(id),
    title          TEXT,
    source         TEXT,
    url            TEXT,
    location       TEXT,
    work_mode      TEXT CHECK (work_mode IN ('remote', 'hybrid', 'onsite')),
    employment     TEXT CHECK (employment IN ('full-time', 'part-time', 'contract', 'temporary', 'internship')),
    salary_min     BIGINT,
    salary_max     BIGINT,
    currency       TEXT,
    pay_period     TEXT CHECK (pay_period IN ('year', 'month', 'day', 'hour')),
    comp           TEXT,
    posted_on      TEXT,
    closes_on      TEXT,
    via_id         BIGINT REFERENCES application(id) ON DELETE SET NULL,
    description    TEXT,
    note           TEXT,
    created_at     TEXT NOT NULL,
    updated_at     TEXT NOT NULL,
    salary_min_gbp BIGINT,
    salary_max_gbp BIGINT,
    gbp_rate       DOUBLE PRECISION,
    gbp_rate_on    TEXT,
    bonus          TEXT,
    equity         TEXT
);

-- The same job posted elsewhere (LinkedIn, a careers page, an agency): an
-- application's other postings, each with what it says. Its own `url` and
-- `description` are its main posting.
CREATE TABLE posting (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES application(id) ON DELETE CASCADE,
    url            TEXT NOT NULL,
    platform       TEXT,
    description    TEXT,
    read_at        TEXT,
    created_at     TEXT NOT NULL,
    updated_at     TEXT NOT NULL
);
CREATE INDEX posting_by_application ON posting (application_id);

CREATE TABLE archive_reason (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    value      TEXT NOT NULL UNIQUE,
    name       TEXT NOT NULL,
    position   BIGINT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX archive_reason_name ON archive_reason (lower(name));

CREATE TABLE process (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES application(id) ON DELETE CASCADE,
    stage_id       BIGINT NOT NULL REFERENCES stage(id),
    position       BIGINT NOT NULL DEFAULT 0,
    status         TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived')),
    archive_reason TEXT REFERENCES archive_reason(value),
    archive_note   TEXT,
    next_action    TEXT,
    next_due       TEXT,
    applied_on     TEXT,
    note           TEXT,
    created_at     TEXT NOT NULL,
    updated_at     TEXT NOT NULL,
    mail_query     TEXT,
    mail_label     TEXT,
    lane_id        BIGINT REFERENCES lane(id) ON DELETE SET NULL
);
CREATE INDEX process_by_column ON process (status, stage_id, position);

CREATE TABLE process_person (
    process_id BIGINT NOT NULL REFERENCES process(id) ON DELETE CASCADE,
    person_id  BIGINT NOT NULL REFERENCES person(id) ON DELETE CASCADE,
    role       TEXT CHECK (role IN ('recruiter', 'hiring-manager', 'interviewer', 'referrer', 'other')),
    PRIMARY KEY (process_id, person_id)
);

CREATE TABLE step (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id BIGINT NOT NULL REFERENCES process(id) ON DELETE CASCADE,
    title      TEXT NOT NULL,
    at         TEXT,
    status     TEXT NOT NULL DEFAULT 'scheduled'
               CHECK (status IN ('scheduled', 'done', 'passed', 'failed', 'cancelled')),
    note       TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    format         TEXT,
    attendees      TEXT
);

CREATE TABLE note (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id BIGINT NOT NULL REFERENCES process(id) ON DELETE CASCADE,
    body       TEXT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    happened_on    TEXT
);

-- Who an interview step is with.
CREATE TABLE step_person (
    step_id   BIGINT NOT NULL,
    person_id BIGINT NOT NULL,
    PRIMARY KEY (step_id, person_id),
    FOREIGN KEY (step_id) REFERENCES step(id) ON DELETE CASCADE,
    FOREIGN KEY (person_id) REFERENCES person(id) ON DELETE CASCADE
);
CREATE INDEX step_person_by_person ON step_person (person_id);

CREATE TABLE document (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    kind        TEXT NOT NULL DEFAULT 'resume'
                CHECK (kind IN ('resume', 'cover-letter', 'portfolio', 'reference', 'screenshot', 'offer',
                              'contract', 'candidate-resource', 'feedback', 'other')),
    description TEXT,
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL
);
CREATE UNIQUE INDEX document_name ON document (lower(name));

CREATE TABLE version (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT NOT NULL REFERENCES document(id) ON DELETE CASCADE,
    number       BIGINT NOT NULL,
    tag          TEXT,
    note         TEXT,
    filename     TEXT NOT NULL,
    content_type TEXT NOT NULL,
    size         BIGINT NOT NULL,
    sha256       TEXT NOT NULL REFERENCES stored_file(sha256),
    created_at   TEXT NOT NULL,
    updated_at   TEXT NOT NULL,
    UNIQUE (document_id, number)
);

CREATE TABLE process_file (
    process_id BIGINT NOT NULL REFERENCES process(id) ON DELETE CASCADE,
    version_id BIGINT NOT NULL REFERENCES version(id),
    added_at   TEXT NOT NULL,
    PRIMARY KEY (process_id, version_id)
);

CREATE TABLE fx_rate (
    currency   TEXT PRIMARY KEY,
    rate       DOUBLE PRECISION NOT NULL,
    rate_on    TEXT NOT NULL,
    fetched_at TEXT NOT NULL
);

CREATE TABLE tag (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL,
    color      TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX tag_name ON tag (lower(name));

CREATE TABLE tagging (
    tag_id    BIGINT NOT NULL REFERENCES tag(id) ON DELETE CASCADE,
    entity    TEXT NOT NULL,
    entity_id BIGINT NOT NULL,
    PRIMARY KEY (tag_id, entity, entity_id)
);
CREATE INDEX tagging_by_entity ON tagging (entity, entity_id);

CREATE TABLE email (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id  BIGINT REFERENCES process(id) ON DELETE CASCADE,
    status      TEXT NOT NULL CHECK (status IN ('linked', 'triage', 'ignored')),
    message_id  TEXT,
    gm_msgid    TEXT UNIQUE,
    gm_thrid    TEXT,
    from_addr   TEXT,
    from_name   TEXT,
    to_addrs    TEXT,
    cc_addrs    TEXT,
    subject     TEXT,
    snippet     TEXT,
    body        TEXT,
    sent_at     TEXT NOT NULL,
    outgoing    BIGINT NOT NULL DEFAULT 0,
    labels      TEXT,
    matched_by  TEXT,
    suggestions TEXT,
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL
);
CREATE INDEX email_by_process ON email (process_id, sent_at);
CREATE INDEX email_by_thread ON email (gm_thrid);
CREATE UNIQUE INDEX email_by_message_id ON email (message_id) WHERE message_id IS NOT NULL;

CREATE TABLE mail_ignore (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       TEXT NOT NULL CHECK (kind IN ('sender', 'domain')),
    value      TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX mail_ignore_value ON mail_ignore (kind, lower(value));

CREATE TABLE setting (
    name  TEXT PRIMARY KEY,
    value TEXT
);

-- General notes: about the search, not one application.
CREATE TABLE memo (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      TEXT,
    body       TEXT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);


CREATE TABLE activity (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at         TEXT NOT NULL,
    entity     TEXT NOT NULL,
    entity_id  BIGINT NOT NULL,
    process_id BIGINT,
    action     TEXT NOT NULL CHECK (action IN ('created', 'updated', 'moved', 'deleted')),
    summary    TEXT NOT NULL,
    changes    TEXT
);
CREATE INDEX activity_by_entity ON activity (entity, entity_id);
CREATE INDEX activity_by_process ON activity (process_id);
